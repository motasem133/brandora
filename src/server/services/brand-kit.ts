import 'server-only'

import { eq } from 'drizzle-orm'
import JSZip from 'jszip'

import { db } from '@/server/db'
import { brandingAssets, generatedFiles, projects } from '@/server/db/schema'
import { objectKey, uploadObject } from '@/server/storage/r2'

/**
 * Packages everything a designer or developer needs to actually use the brand:
 * logos in usable formats, colour tokens for code, font links, and a one-page
 * summary. This is what makes the output a deliverable rather than a preview.
 */
export async function buildBrandKit(projectId: string, files: Map<string, Buffer>) {
  const [project] = await db.select().from(projects).where(eq(projects.id, projectId)).limit(1)
  const [branding] = await db
    .select()
    .from(brandingAssets)
    .where(eq(brandingAssets.projectId, projectId))
    .limit(1)

  if (!project || !branding) return null

  const palette = branding.colorPalette
  const fonts = branding.fontRecommendations
  const name = project.businessName || branding.businessNameIdeas[0]?.name || project.title

  const zip = new JSZip()

  const logoDir = zip.folder('logo')!
  const socialDir = zip.folder('social')!
  const paletteDir = zip.folder('palette')!

  for (const [filename, buffer] of files) {
    if (filename.startsWith('social-') || filename.startsWith('og-') || filename.startsWith('banner-')) {
      socialDir.file(filename.replace(/^(social|og|banner)-/, ''), buffer)
    } else {
      logoDir.file(filename, buffer)
    }
  }

  if (palette) {
    paletteDir.file('tokens.json', JSON.stringify(palette, null, 2))
    paletteDir.file('tokens.css', cssTokens(palette, fonts))
    paletteDir.file('palette.ase.txt', aseReadable(palette))
  }

  if (fonts) {
    zip.file('FONTS.txt', fontsReadme(fonts))
  }

  zip.file('BRAND-GUIDE.md', brandGuide({ name, branding }))

  const buffer = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' })
  const key = objectKey(projectId, 'brand-kit.zip')

  await uploadObject({
    key,
    body: buffer,
    contentType: 'application/zip',
    // The kit is rebuilt whenever assets change, so it must not be cached hard.
    cacheControl: 'private, max-age=0, must-revalidate',
  })

  await db
    .insert(generatedFiles)
    .values({
      projectId,
      kind: 'brand_kit_zip',
      r2Key: key,
      mimeType: 'application/zip',
      sizeBytes: buffer.byteLength,
      metadata: { entries: Object.keys(zip.files).length },
    })
    .returning()

  return { key, sizeBytes: buffer.byteLength }
}

function cssTokens(palette: Record<string, string>, fonts: Record<string, string> | null) {
  const colours = Object.entries(palette)
    .map(([name, value]) => `  --brand-${name}: ${value};`)
    .join('\n')

  const families = fonts
    ? Object.entries(fonts)
        .filter(([, value]) => Boolean(value))
        .map(([role, family]) => `  --font-${role}: '${family}', sans-serif;`)
        .join('\n')
    : ''

  return `:root {\n${colours}\n${families}\n}\n`
}

function aseReadable(palette: Record<string, string>) {
  return Object.entries(palette)
    .map(([name, hex]) => {
      const r = parseInt(hex.slice(1, 3), 16)
      const g = parseInt(hex.slice(3, 5), 16)
      const b = parseInt(hex.slice(5, 7), 16)
      return `${name}\t${hex.toUpperCase()}\tRGB(${r}, ${g}, ${b})`
    })
    .join('\n')
}

function fontsReadme(fonts: Record<string, string>) {
  const lines = Object.entries(fonts)
    .filter(([, family]) => Boolean(family))
    .map(([role, family]) => {
      const slug = family.replace(/\s+/g, '+')
      return `${role}: ${family}\n  https://fonts.google.com/specimen/${slug}\n  @import url('https://fonts.googleapis.com/css2?family=${slug}:wght@400;500;600;700&display=swap');`
    })

  return `Fonts\n=====\n\n${lines.join('\n\n')}\n`
}

function brandGuide({
  name,
  branding,
}: {
  name: string
  branding: typeof brandingAssets.$inferSelect
}) {
  const palette = branding.colorPalette
  const fonts = branding.fontRecommendations

  return `# ${name} — Brand Guide

## Slogan
${branding.slogan ?? '—'}

## Brand story
${branding.brandStory ?? '—'}

## Voice
${branding.brandVoice ?? '—'}

## Values
${branding.brandValues.map((value) => `- ${value}`).join('\n')}

## Colour palette
${palette ? Object.entries(palette).map(([role, hex]) => `- **${role}**: ${hex}`).join('\n') : '—'}

## Typography
${fonts ? Object.entries(fonts).filter(([, f]) => f).map(([role, family]) => `- **${role}**: ${family}`).join('\n') : '—'}

## Name alternatives considered
${branding.businessNameIdeas.map((idea) => `- **${idea.name}** — ${idea.rationale}`).join('\n')}

---
Generated by Brandora.
`
}
